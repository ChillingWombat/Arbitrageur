//! Multi-Asset Cross-Perp Skew Trading with Dynamic Volatility Surface Inter-Exchange Dispersion.
//!
//! Provides:
//! - Continuous SVI (Stochastic Volatility Inspired) and synthetic volatility skew parameterization.
//! - Multi-dimensional cross-perp skew evaluation: funding rate basis dislocation, kinematic funding velocity divergence,
//!   and asymmetric orderbook depth skew.
//! - Delta-neutral, vega-hedged skew dispersion signals between fragmented perpetual venues (Hyperliquid, Lighter, Orderly, Binance)
//!   and options volatility surfaces (Deribit).

use arbitrageur_core::types::VenueId;
pub use arbitrageur_math::margin_deleveraging::SecondOrderMarginHessian;
pub use arbitrageur_math::variance_swap::SviParameters;
use serde::{Deserialize, Serialize};

/// Configuration for the Cross-Perp Skew Dispersion Engine.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CrossPerpSkewConfig {
    pub enabled: bool,
    /// Minimum z-score to trigger long/short entry (e.g. 2.0 standard deviations).
    pub entry_z_score: f64,
    /// Exit / unwind threshold (e.g. 0.50 standard deviations).
    pub exit_z_score: f64,
    /// Minimum funding spread hurdle in basis points (e.g. 5.0 bps).
    pub min_funding_spread_bps: f64,
    /// Minimum expected edge hurdle in basis points (e.g. 8.0 bps).
    pub min_edge_bps: f64,
    /// Maximum holding time before forced mean-reversion exit (seconds).
    pub max_holding_sec: u64,
    /// Weight assigned to standardized funding rate basis dislocation.
    pub weight_funding: f64,
    /// Weight assigned to asymmetric orderbook depth skew difference.
    pub weight_depth_skew: f64,
    /// Weight assigned to kinematic funding velocity differential.
    pub weight_velocity: f64,
    /// Exponential decay factor for rolling mean/variance tracking (e.g. 0.95).
    pub rolling_decay: f64,
}

impl Default for CrossPerpSkewConfig {
    fn default() -> Self {
        Self {
            enabled: true,
            entry_z_score: 2.0,
            exit_z_score: 0.5,
            min_funding_spread_bps: 5.0,
            min_edge_bps: 8.0,
            max_holding_sec: 28800, // 8 hours
            weight_funding: 0.50,
            weight_depth_skew: 0.30,
            weight_velocity: 0.20,
            rolling_decay: 0.95,
        }
    }
}

/// Input snapshot capturing cross-venue perp state for an asset.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CrossPerpSkewSnapshot {
    pub symbol: String,
    pub venue_a: VenueId,
    pub venue_b: VenueId,
    /// Annualized or 8-hour funding rate on Venue A in basis points.
    pub funding_rate_a_bps: f64,
    /// Annualized or 8-hour funding rate on Venue B in basis points.
    pub funding_rate_b_bps: f64,
    /// Kinematic funding velocity dF/dt on Venue A in basis points per hour.
    pub funding_velocity_a_bps_per_hr: f64,
    /// Kinematic funding velocity dF/dt on Venue B in basis points per hour.
    pub funding_velocity_b_bps_per_hr: f64,
    /// Total cumulative bid depth on Venue A (e.g. top 5 levels in USD).
    pub depth_bid_a: f64,
    /// Total cumulative ask depth on Venue A in USD.
    pub depth_ask_a: f64,
    /// Total cumulative bid depth on Venue B in USD.
    pub depth_bid_b: f64,
    /// Total cumulative ask depth on Venue B in USD.
    pub depth_ask_b: f64,
}

/// Computed cross-perp skew metrics.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct CrossPerpSkewMetrics {
    pub funding_spread_bps: f64,
    pub velocity_spread_bps_per_hr: f64,
    pub depth_skew_a: f64,
    pub depth_skew_b: f64,
    pub depth_skew_diff: f64,
    pub composite_skew: f64,
    pub z_score: f64,
}

/// Signal generated by the Cross-Perp Skew Dispersion Engine.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum CrossPerpSignal {
    Hold,
    EnterLongShort {
        long_venue: VenueId,
        short_venue: VenueId,
        symbol: String,
        composite_skew: f64,
        expected_edge_bps: f64,
        action: &'static str,
    },
    Unwind {
        symbol: String,
        reason: String,
    },
}

/// Cross-Perp Volatility Skew Dispersion Engine.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CrossPerpSkewDispersionEngine {
    pub config: CrossPerpSkewConfig,
    /// Rolling mean of funding spread (F_A - F_B).
    pub mean_funding_spread: f64,
    /// Rolling variance of funding spread.
    pub var_funding_spread: f64,
    /// Number of observations processed.
    pub count: usize,
    /// Set of symbols with currently active dispersion positions.
    pub active_positions: std::collections::HashSet<String>,
}

impl Default for CrossPerpSkewDispersionEngine {
    fn default() -> Self {
        Self::new(CrossPerpSkewConfig::default())
    }
}

impl CrossPerpSkewDispersionEngine {
    pub fn new(config: CrossPerpSkewConfig) -> Self {
        Self {
            config,
            mean_funding_spread: 0.0,
            var_funding_spread: 1.0,
            count: 0,
            active_positions: std::collections::HashSet::new(),
        }
    }

    pub fn record_entry(&mut self, symbol: &str) {
        self.active_positions.insert(symbol.to_string());
    }

    pub fn record_unwind(&mut self, symbol: &str) {
        self.active_positions.remove(symbol);
    }

    pub fn has_active_position(&self, symbol: &str) -> bool {
        self.active_positions.contains(symbol)
    }

    /// Updates rolling statistics and evaluates a cross-perp market snapshot.
    pub fn evaluate_snapshot(
        &mut self,
        snapshot: &CrossPerpSkewSnapshot,
    ) -> (CrossPerpSignal, CrossPerpSkewMetrics) {
        if !self.config.enabled {
            let metrics = CrossPerpSkewMetrics {
                funding_spread_bps: 0.0,
                velocity_spread_bps_per_hr: 0.0,
                depth_skew_a: 0.0,
                depth_skew_b: 0.0,
                depth_skew_diff: 0.0,
                composite_skew: 0.0,
                z_score: 0.0,
            };
            return (CrossPerpSignal::Hold, metrics);
        }

        // 1. Funding spread: Delta F = F_A - F_B
        let funding_spread = snapshot.funding_rate_a_bps - snapshot.funding_rate_b_bps;

        // 2. Online Welford / EMA update of funding spread mean & variance
        self.count += 1;
        if self.count == 1 {
            self.mean_funding_spread = funding_spread;
            self.var_funding_spread = 1.0;
        } else {
            let alpha = 1.0 - self.config.rolling_decay;
            let diff = funding_spread - self.mean_funding_spread;
            self.mean_funding_spread += alpha * diff;
            self.var_funding_spread = (1.0 - alpha) * self.var_funding_spread + alpha * diff * diff;
        }

        let std_funding = self.var_funding_spread.sqrt().max(1e-4);
        let z_funding = (funding_spread - self.mean_funding_spread) / std_funding;

        // 3. Velocity spread: Delta v_F = v_A - v_B
        let vel_spread =
            snapshot.funding_velocity_a_bps_per_hr - snapshot.funding_velocity_b_bps_per_hr;
        let z_velocity = (vel_spread / 5.0).clamp(-5.0, 5.0);

        // 4. Orderbook depth skew: Skew_depth = (V_bid - V_ask) / (V_bid + V_ask) in [-1, 1]
        let depth_sum_a = snapshot.depth_bid_a + snapshot.depth_ask_a;
        let depth_skew_a = if depth_sum_a > 1e-6 {
            (snapshot.depth_bid_a - snapshot.depth_ask_a) / depth_sum_a
        } else {
            0.0
        };

        let depth_sum_b = snapshot.depth_bid_b + snapshot.depth_ask_b;
        let depth_skew_b = if depth_sum_b > 1e-6 {
            (snapshot.depth_bid_b - snapshot.depth_ask_b) / depth_sum_b
        } else {
            0.0
        };

        let depth_skew_diff = depth_skew_a - depth_skew_b;

        // 5. Composite Skew Indicator: Psi_skew
        let w_f = self.config.weight_funding;
        let w_d = self.config.weight_depth_skew;
        let w_v = self.config.weight_velocity;

        let composite_skew = w_f * z_funding + w_d * depth_skew_diff + w_v * z_velocity;
        let z_composite = composite_skew;

        let metrics = CrossPerpSkewMetrics {
            funding_spread_bps: funding_spread,
            velocity_spread_bps_per_hr: vel_spread,
            depth_skew_a,
            depth_skew_b,
            depth_skew_diff,
            composite_skew,
            z_score: z_composite,
        };

        // 6. Signal Evaluation
        let entry_z = self.config.entry_z_score;
        let exit_z = self.config.exit_z_score;
        let min_spread = self.config.min_funding_spread_bps;

        // If z_score < -entry_z: Venue A perp is oversold/underpriced relative to B.
        // It pays less funding (or receives funding) and has stronger relative bid support -> Long A, Short B.
        if z_composite <= -entry_z && funding_spread.abs() >= min_spread {
            let edge = funding_spread.abs() + depth_skew_diff.abs() * 5.0;
            if edge >= self.config.min_edge_bps {
                self.active_positions.insert(snapshot.symbol.clone());
                return (
                    CrossPerpSignal::EnterLongShort {
                        long_venue: snapshot.venue_a.clone(),
                        short_venue: snapshot.venue_b.clone(),
                        symbol: snapshot.symbol.clone(),
                        composite_skew,
                        expected_edge_bps: edge,
                        action: "ENTER_LONG_A_SHORT_B",
                    },
                    metrics,
                );
            }
        }

        // If z_score > entry_z: Venue A perp is overbought/overpriced relative to B.
        // It pays excessive funding and has higher ask pressure -> Short A, Long B.
        if z_composite >= entry_z && funding_spread.abs() >= min_spread {
            let edge = funding_spread.abs() + depth_skew_diff.abs() * 5.0;
            if edge >= self.config.min_edge_bps {
                self.active_positions.insert(snapshot.symbol.clone());
                return (
                    CrossPerpSignal::EnterLongShort {
                        long_venue: snapshot.venue_b.clone(),
                        short_venue: snapshot.venue_a.clone(),
                        symbol: snapshot.symbol.clone(),
                        composite_skew,
                        expected_edge_bps: edge,
                        action: "ENTER_LONG_B_SHORT_A",
                    },
                    metrics,
                );
            }
        }

        // Mean-reversion exit condition
        if z_composite.abs() <= exit_z && self.active_positions.contains(&snapshot.symbol) {
            self.active_positions.remove(&snapshot.symbol);
            return (
                CrossPerpSignal::Unwind {
                    symbol: snapshot.symbol.clone(),
                    reason: format!(
                        "Skew converged: z={:.2} within exit threshold {:.2}",
                        z_composite, exit_z
                    ),
                },
                metrics,
            );
        }

        (CrossPerpSignal::Hold, metrics)
    }

    /// Evaluates snapshot with second-order margin Hessian solvency guard across segregated venue balances.
    /// If candidate trade would breach the solvency barrier under extreme spot shocks, entry is aborted fail-closed.
    #[allow(clippy::too_many_arguments)]
    pub fn evaluate_snapshot_with_solvency(
        &mut self,
        snapshot: &CrossPerpSkewSnapshot,
        free_margin_a: f64,
        mmr_a: f64,
        free_margin_b: f64,
        mmr_b: f64,
        candidate_notional_usd: f64,
        spot_price: f64,
        is_inverse_a: bool,
        is_inverse_b: bool,
        solvency_hessian: &SecondOrderMarginHessian,
    ) -> (CrossPerpSignal, CrossPerpSkewMetrics) {
        let (raw_signal, metrics) = self.evaluate_snapshot(snapshot);
        match &raw_signal {
            CrossPerpSignal::EnterLongShort { long_venue, .. } => {
                let is_long_a = long_venue == &snapshot.venue_a;
                // Check Venue A solvency
                let res_a = solvency_hessian.check_venue_solvency_barrier(
                    free_margin_a,
                    mmr_a,
                    candidate_notional_usd,
                    spot_price,
                    is_long_a,
                    is_inverse_a,
                );
                if let Err(e) = res_a {
                    tracing::warn!(
                        "CrossPerpSkew entry aborted on {}: Venue A ({:?}) {}",
                        snapshot.symbol,
                        snapshot.venue_a,
                        e
                    );
                    self.active_positions.remove(&snapshot.symbol);
                    return (CrossPerpSignal::Hold, metrics);
                }

                // Check Venue B solvency
                let is_long_b = long_venue == &snapshot.venue_b;
                let res_b = solvency_hessian.check_venue_solvency_barrier(
                    free_margin_b,
                    mmr_b,
                    candidate_notional_usd,
                    spot_price,
                    is_long_b,
                    is_inverse_b,
                );
                if let Err(e) = res_b {
                    tracing::warn!(
                        "CrossPerpSkew entry aborted on {}: Venue B ({:?}) {}",
                        snapshot.symbol,
                        snapshot.venue_b,
                        e
                    );
                    self.active_positions.remove(&snapshot.symbol);
                    return (CrossPerpSignal::Hold, metrics);
                }

                (raw_signal, metrics)
            }
            _ => (raw_signal, metrics),
        }
    }

    /// Evaluates 25-delta Risk Reversal dislocation between two calibrated SVI surfaces:
    /// Returns (RR_A, RR_B, Delta_RR = RR_A - RR_B).
    pub fn compute_skew_dislocation(
        &self,
        svi_a: &SviParameters,
        svi_b: &SviParameters,
        tau_years: f64,
    ) -> (f64, f64, f64) {
        let rr_a = svi_a.risk_reversal_25(tau_years);
        let rr_b = svi_b.risk_reversal_25(tau_years);
        let dislocation = rr_a - rr_b;
        (rr_a, rr_b, dislocation)
    }

    /// Computes delta-neutral, vega-hedged weights for cross-venue skew arbitrage:
    /// Long Risk Reversal on underpriced venue, Short Risk Reversal on overpriced venue.
    pub fn solve_delta_vega_neutral_weights(&self, rr_a: f64, rr_b: f64) -> [f64; 4] {
        if rr_a > rr_b {
            // Venue A is call-skewed (overpriced RR), Venue B is put-skewed (underpriced RR)
            // Short RR on Venue A (Short Call, Long Put), Long RR on Venue B (Long Call, Short Put)
            [-1.0, 1.0, 1.0, -1.0]
        } else {
            // Venue A is underpriced RR, Venue B is overpriced RR
            // Long RR on Venue A, Short RR on Venue B
            [1.0, -1.0, -1.0, 1.0]
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_svi_total_variance_and_iv() {
        let svi = SviParameters::new(0.04, 0.15, -0.25, 0.0, 0.10);
        let tau = 0.25; // 3 months
        let iv_atm = svi.atm_volatility(tau);
        assert!(
            iv_atm > 0.30 && iv_atm < 0.60,
            "ATM IV reasonable: {}",
            iv_atm
        );

        let iv_otm_put = svi.implied_volatility(-0.20, tau);
        let iv_otm_call = svi.implied_volatility(0.20, tau);
        // With negative rho (-0.25), puts have higher IV than calls (equity/crypto skew)
        assert!(
            iv_otm_put > iv_otm_call,
            "Put skew verified: put={}, call={}",
            iv_otm_put,
            iv_otm_call
        );

        let rr25 = svi.risk_reversal_25(tau);
        assert!(
            rr25 < 0.0,
            "Risk reversal negative for negative rho: {}",
            rr25
        );

        let bf25 = svi.butterfly_25(tau);
        assert!(bf25 > 0.0, "Butterfly positive due to curvature: {}", bf25);
    }

    #[test]
    fn test_cross_perp_skew_engine_neutral_hold() {
        let mut engine = CrossPerpSkewDispersionEngine::default();
        let snap = CrossPerpSkewSnapshot {
            symbol: "BTC-PERP".to_string(),
            venue_a: VenueId("hyperliquid".to_string()),
            venue_b: VenueId("lighter".to_string()),
            funding_rate_a_bps: 10.0,
            funding_rate_b_bps: 10.0,
            funding_velocity_a_bps_per_hr: 0.0,
            funding_velocity_b_bps_per_hr: 0.0,
            depth_bid_a: 100_000.0,
            depth_ask_a: 100_000.0,
            depth_bid_b: 100_000.0,
            depth_ask_b: 100_000.0,
        };

        let (signal, metrics) = engine.evaluate_snapshot(&snap);
        assert_eq!(metrics.funding_spread_bps, 0.0);
        assert_eq!(metrics.depth_skew_diff, 0.0);
        assert_eq!(signal, CrossPerpSignal::Hold);
    }

    #[test]
    fn test_cross_perp_skew_engine_entry_signals() {
        let mut engine = CrossPerpSkewDispersionEngine {
            mean_funding_spread: 0.0,
            var_funding_spread: 4.0, // std = 2.0
            count: 10,
            ..Default::default()
        };

        // Severe negative funding spread: F_A = -15 bps, F_B = 10 bps -> spread = -25 bps
        // Ask-heavy on A (oversold), bid-heavy on B -> Strong Long A, Short B signal
        let snap_neg = CrossPerpSkewSnapshot {
            symbol: "ETH-PERP".to_string(),
            venue_a: VenueId("hyperliquid".to_string()),
            venue_b: VenueId("lighter".to_string()),
            funding_rate_a_bps: -15.0,
            funding_rate_b_bps: 10.0,
            funding_velocity_a_bps_per_hr: -2.0,
            funding_velocity_b_bps_per_hr: 2.0,
            depth_bid_a: 50_000.0,
            depth_ask_a: 200_000.0, // strong ask skew on A (oversold)
            depth_bid_b: 200_000.0,
            depth_ask_b: 50_000.0, // strong bid skew on B
        };

        let (signal, metrics) = engine.evaluate_snapshot(&snap_neg);
        assert!(metrics.funding_spread_bps < -20.0);
        assert!(metrics.z_score < -2.0);

        match signal {
            CrossPerpSignal::EnterLongShort {
                long_venue,
                short_venue,
                symbol,
                action,
                ..
            } => {
                assert_eq!(long_venue.0, "hyperliquid");
                assert_eq!(short_venue.0, "lighter");
                assert_eq!(symbol, "ETH-PERP");
                assert_eq!(action, "ENTER_LONG_A_SHORT_B");
            }
            other => panic!("Expected EnterLongShort, got {:?}", other),
        }

        // Now test mean reversion unwind
        let snap_converged = CrossPerpSkewSnapshot {
            symbol: "ETH-PERP".to_string(),
            venue_a: VenueId("hyperliquid".to_string()),
            venue_b: VenueId("lighter".to_string()),
            funding_rate_a_bps: 0.1,
            funding_rate_b_bps: 0.0,
            funding_velocity_a_bps_per_hr: 0.0,
            funding_velocity_b_bps_per_hr: 0.0,
            depth_bid_a: 100_000.0,
            depth_ask_a: 100_000.0,
            depth_bid_b: 100_000.0,
            depth_ask_b: 100_000.0,
        };

        let (unwind_sig, unwind_met) = engine.evaluate_snapshot(&snap_converged);
        assert!(unwind_met.z_score.abs() <= 0.5);
        match unwind_sig {
            CrossPerpSignal::Unwind { symbol, reason } => {
                assert_eq!(symbol, "ETH-PERP");
                assert!(reason.contains("Skew converged"));
            }
            other => panic!("Expected Unwind signal, got {:?}", other),
        }
    }

    #[test]
    fn test_skew_dislocation_and_hedge_weights() {
        let engine = CrossPerpSkewDispersionEngine::default();
        let svi_a = SviParameters::new(0.04, 0.15, -0.40, 0.0, 0.10); // severe put skew
        let svi_b = SviParameters::new(0.04, 0.15, 0.10, 0.0, 0.10); // slight call skew

        let (rr_a, rr_b, disloc) = engine.compute_skew_dislocation(&svi_a, &svi_b, 0.25);
        assert!(rr_a < rr_b, "RR_A should be lower than RR_B");
        assert!(disloc < 0.0, "Dislocation is negative");

        let weights = engine.solve_delta_vega_neutral_weights(rr_a, rr_b);
        assert_eq!(weights, [1.0, -1.0, -1.0, 1.0]);
    }

    #[test]
    fn test_second_order_margin_solvency_barrier() {
        let mut engine = CrossPerpSkewDispersionEngine {
            mean_funding_spread: 0.0,
            var_funding_spread: 4.0,
            count: 10,
            ..Default::default()
        };
        let hessian = SecondOrderMarginHessian::default();

        let snap = CrossPerpSkewSnapshot {
            symbol: "ETH-PERP".to_string(),
            venue_a: VenueId("hyperliquid".to_string()),
            venue_b: VenueId("lighter".to_string()),
            funding_rate_a_bps: -15.0,
            funding_rate_b_bps: 10.0,
            funding_velocity_a_bps_per_hr: -2.0,
            funding_velocity_b_bps_per_hr: 2.0,
            depth_bid_a: 50_000.0,
            depth_ask_a: 200_000.0,
            depth_bid_b: 200_000.0,
            depth_ask_b: 50_000.0,
        };

        // Case 1: Healthy free margin ($10,000 on both venues, MMR $500, notional $10,000)
        let (sig_ok, _) = engine.evaluate_snapshot_with_solvency(
            &snap, 10_000.0, // free A
            500.0,    // mmr A
            10_000.0, // free B
            500.0,    // mmr B
            10_000.0, // notional
            3000.0,   // spot
            false, false, &hessian,
        );
        match sig_ok {
            CrossPerpSignal::EnterLongShort { action, .. } => {
                assert_eq!(action, "ENTER_LONG_A_SHORT_B");
            }
            other => panic!(
                "Expected EnterLongShort with healthy margin, got {:?}",
                other
            ),
        }

        // Case 2: Insufficient free margin on Venue A ($200 free margin vs 35% shock of $10,000 notional = $3,500 loss)
        let mut engine_low_margin = CrossPerpSkewDispersionEngine {
            mean_funding_spread: 0.0,
            var_funding_spread: 4.0,
            count: 10,
            ..Default::default()
        };
        let (sig_blocked, _) = engine_low_margin.evaluate_snapshot_with_solvency(
            &snap, 200.0,    // insufficient free margin A
            500.0,    // mmr A
            10_000.0, // free B
            500.0,    // mmr B
            10_000.0, // notional
            3000.0,   // spot
            false, false, &hessian,
        );
        assert_eq!(
            sig_blocked,
            CrossPerpSignal::Hold,
            "Entry must be aborted when solvency barrier is breached"
        );
    }
}
