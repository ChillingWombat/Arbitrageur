//! Exotic Multi-Asset Crypto Options & Rough-LSV Dispersion Engine.
//!
//! Models multi-asset cross-sectional volatility dispersion across crypto index baskets (BTC, ETH, SOL)
//! and individual component options. Features:
//! 1. Non-parametric Dupire leverage function L^i(S, t) matching market marginal local volatility.
//! 2. Model-free implied correlation swap strike rho_implied*(T) extracted from replicated variance swap strips.
//! 3. Cross-sectional dispersion trading signal generation (Long/Short correlation arbitrage).
//! 4. Dynamic Extreme Margin Cushion (DEMC) under Clayton-Gumbel extreme value copula with tail dependence.

use serde::{Deserialize, Serialize};

/// Trading recommendation generated by the rough-LSV dispersion engine.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum DispersionSignalType {
    /// Implied correlation > realized correlation + hurdle: sell basket vol, buy component vol.
    ShortCorrelationDispersion,
    /// Implied correlation < realized correlation - hurdle: buy basket vol, sell component vol.
    LongCorrelationDispersion,
    /// Implied correlation inside no-arbitrage band.
    Neutral,
}

/// Configuration parameters for the Rough-LSV Dispersion Engine.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct RoughLsvDispersionConfig {
    /// Minimum correlation mispricing hurdle to trigger execution (default: 0.08, or 8%).
    pub correlation_hurdle: f64,
    /// Risk aversion / margin sensitivity coefficient kappa_margin for DEMC (default: 0.35).
    pub demc_kappa: f64,
    /// Upper tail dependence weighting alpha_U in DEMC (default: 0.50).
    pub demc_alpha_u: f64,
    /// Minimum required margin cushion multiplier floor (default: 1.15x).
    pub min_margin_cushion: f64,
    /// Maximum allowed margin cushion multiplier cap (default: 3.50x).
    pub max_margin_cushion: f64,
}

impl Default for RoughLsvDispersionConfig {
    fn default() -> Self {
        Self {
            correlation_hurdle: 0.08,
            demc_kappa: 0.35,
            demc_alpha_u: 0.50,
            min_margin_cushion: 1.15,
            max_margin_cushion: 3.50,
        }
    }
}

/// A component crypto asset in the dispersion basket (e.g. BTC, ETH, SOL).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BasketComponent {
    pub symbol: String,
    /// Basket weight w_i (sum of w_i should equal 1.0).
    pub weight: f64,
    /// Annualized implied volatility sigma_i (e.g. 0.60 for 60%).
    pub implied_vol: f64,
    /// Prevailing spot price S_i in USD.
    pub spot_price: f64,
}

/// Complete dispersion trade recommendation and margin risk metrics.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct DispersionEvaluation {
    pub signal_type: DispersionSignalType,
    /// Model-free fair implied correlation strike rho_implied*(T).
    pub implied_correlation_strike: f64,
    /// Historical/realized correlation benchmark rho_realized.
    pub realized_correlation: f64,
    /// Correlation dislocation spread Delta rho = rho_implied - rho_realized.
    pub correlation_spread: f64,
    /// Dynamic Extreme Margin Cushion (DEMC) multiplier (>= 1.0).
    pub demc_margin_cushion: f64,
    /// Clayton lower tail dependence lambda_L.
    pub lower_tail_dependence: f64,
    /// Gumbel upper tail dependence lambda_U.
    pub upper_tail_dependence: f64,
    /// Expected annualized dispersion alpha in basis points.
    pub expected_dispersion_alpha_bps: f64,
}

/// The Rough-LSV Dispersion Engine.
pub struct RoughLsvDispersionEngine {
    pub config: RoughLsvDispersionConfig,
}

impl RoughLsvDispersionEngine {
    pub fn new(config: RoughLsvDispersionConfig) -> Self {
        Self { config }
    }

    /// Evaluates non-parametric Dupire leverage function L^i(S, t) = sigma_Dupire / sqrt(E[V_t | S_t = S]).
    pub fn evaluate_dupire_leverage(
        &self,
        dupire_local_vol: f64,
        conditional_expected_variance: f64,
    ) -> f64 {
        let denom = conditional_expected_variance.max(1e-6).sqrt();
        (dupire_local_vol / denom).max(0.01)
    }

    /// Calculates the model-free implied correlation strike rho_implied*(T)
    /// from the basket variance swap strike and single-asset component variance swap strikes:
    /// sigma_basket^2 = sum_i w_i^2 sigma_i^2 + 2 sum_{i < j} w_i w_j rho sigma_i sigma_j.
    pub fn compute_model_free_implied_correlation(
        &self,
        components: &[BasketComponent],
        basket_implied_vol: f64,
    ) -> anyhow::Result<f64> {
        if components.len() < 2 {
            anyhow::bail!("Dispersion basket requires at least 2 components");
        }

        let basket_var = basket_implied_vol.powi(2);

        let mut weighted_single_var_sum = 0.0;
        let mut cross_vol_denom = 0.0;

        for (i, c_i) in components.iter().enumerate() {
            weighted_single_var_sum += c_i.weight.powi(2) * c_i.implied_vol.powi(2);

            for c_j in components.iter().skip(i + 1) {
                cross_vol_denom +=
                    2.0 * c_i.weight * c_j.weight * c_i.implied_vol * c_j.implied_vol;
            }
        }

        if cross_vol_denom <= 1e-8 {
            anyhow::bail!(
                "Cross-asset volatility denominator too small for correlation extraction"
            );
        }

        let rho_implied = (basket_var - weighted_single_var_sum) / cross_vol_denom;
        // Theoretical correlation bound [-1.0, 1.0]
        Ok(rho_implied.clamp(-1.0, 1.0))
    }

    /// Calculates Dynamic Extreme Margin Cushion (DEMC) under Clayton-Gumbel extreme value copula.
    /// lambda_L = 2^(-1 / theta_C), lambda_U = 2 - 2^(1 / theta_G).
    /// DEMC = 1.0 + kappa * (lambda_L + alpha_U * lambda_U) * sqrt(leverage_ratio).
    pub fn calculate_demc_margin_cushion(
        &self,
        clayton_theta: f64,
        gumbel_theta: f64,
        portfolio_leverage_ratio: f64,
    ) -> (f64, f64, f64) {
        // Clayton parameter theta_C > 0 gives lower tail dependence lambda_L
        let theta_c_safe = clayton_theta.max(0.01);
        let lambda_l = 2.0f64.powf(-1.0 / theta_c_safe);

        // Gumbel parameter theta_G >= 1 gives upper tail dependence lambda_U
        let theta_g_safe = gumbel_theta.max(1.0);
        let lambda_u = 2.0 - 2.0f64.powf(1.0 / theta_g_safe);

        let lev_factor = portfolio_leverage_ratio.max(1.0).sqrt();
        let tail_risk = lambda_l + self.config.demc_alpha_u * lambda_u;
        let cushion = 1.0 + self.config.demc_kappa * tail_risk * lev_factor;

        let clamped_cushion = cushion.clamp(
            self.config.min_margin_cushion,
            self.config.max_margin_cushion,
        );

        (clamped_cushion, lambda_l, lambda_u)
    }

    /// Evaluates full dispersion opportunity across the basket.
    pub fn evaluate_dispersion(
        &self,
        components: &[BasketComponent],
        basket_implied_vol: f64,
        realized_correlation: f64,
        clayton_theta: f64,
        gumbel_theta: f64,
        portfolio_leverage_ratio: f64,
    ) -> anyhow::Result<DispersionEvaluation> {
        let rho_implied =
            self.compute_model_free_implied_correlation(components, basket_implied_vol)?;
        let correlation_spread = rho_implied - realized_correlation;

        let signal_type = if correlation_spread > self.config.correlation_hurdle {
            DispersionSignalType::ShortCorrelationDispersion
        } else if correlation_spread < -self.config.correlation_hurdle {
            DispersionSignalType::LongCorrelationDispersion
        } else {
            DispersionSignalType::Neutral
        };

        let (cushion, lambda_l, lambda_u) = self.calculate_demc_margin_cushion(
            clayton_theta,
            gumbel_theta,
            portfolio_leverage_ratio,
        );

        // Expected alpha proportional to correlation spread magnitude in basis points
        let alpha_bps = correlation_spread.abs() * 10000.0 * 0.5;

        Ok(DispersionEvaluation {
            signal_type,
            implied_correlation_strike: rho_implied,
            realized_correlation,
            correlation_spread,
            demc_margin_cushion: cushion,
            lower_tail_dependence: lambda_l,
            upper_tail_dependence: lambda_u,
            expected_dispersion_alpha_bps: alpha_bps,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_dupire_leverage_function() {
        let engine = RoughLsvDispersionEngine::new(RoughLsvDispersionConfig::default());
        let l = engine.evaluate_dupire_leverage(0.60, 0.36);
        // sqrt(0.36) = 0.60 -> L = 0.60 / 0.60 = 1.0
        assert!((l - 1.0).abs() < 1e-4);
    }

    #[test]
    fn test_model_free_implied_correlation_calculation() {
        let engine = RoughLsvDispersionEngine::new(RoughLsvDispersionConfig::default());
        // 2 equal weight assets: w1 = 0.5, w2 = 0.5, sigma1 = 0.60, sigma2 = 0.80
        let components = vec![
            BasketComponent {
                symbol: "BTC".into(),
                weight: 0.5,
                implied_vol: 0.60,
                spot_price: 65000.0,
            },
            BasketComponent {
                symbol: "ETH".into(),
                weight: 0.5,
                implied_vol: 0.80,
                spot_price: 3500.0,
            },
        ];

        // If rho = 0.70:
        // sigma_basket^2 = 0.25*0.36 + 0.25*0.64 + 2*0.25*0.60*0.80*0.70 = 0.09 + 0.16 + 0.168 = 0.418
        // basket_vol = sqrt(0.418) = 0.646529
        let basket_vol = 0.418f64.sqrt();
        let rho_calc = engine
            .compute_model_free_implied_correlation(&components, basket_vol)
            .unwrap();

        assert!((rho_calc - 0.70).abs() < 1e-3);
    }

    #[test]
    fn test_dispersion_signal_and_demc_cushion() {
        let engine = RoughLsvDispersionEngine::new(RoughLsvDispersionConfig::default());
        let components = vec![
            BasketComponent {
                symbol: "BTC".into(),
                weight: 0.6,
                implied_vol: 0.55,
                spot_price: 65000.0,
            },
            BasketComponent {
                symbol: "ETH".into(),
                weight: 0.3,
                implied_vol: 0.75,
                spot_price: 3500.0,
            },
            BasketComponent {
                symbol: "SOL".into(),
                weight: 0.1,
                implied_vol: 0.90,
                spot_price: 150.0,
            },
        ];

        // High basket vol -> Implied correlation high -> Short correlation dispersion
        let eval = engine
            .evaluate_dispersion(
                &components,
                0.72, // High basket vol
                0.45, // Realized correlation
                2.0,  // Clayton theta (severe lower tail dependence)
                1.5,  // Gumbel theta
                3.0,  // 3x leverage
            )
            .unwrap();

        assert_eq!(
            eval.signal_type,
            DispersionSignalType::ShortCorrelationDispersion
        );
        assert!(eval.correlation_spread > 0.08);
        assert!(eval.demc_margin_cushion > 1.25);
        assert!(eval.lower_tail_dependence > 0.60);
    }
}
