//! Path Signature Calibrated Cross-Tenor Perpetual Funding Rate Carry & Basis Dispersion Engine.
//!
//! Evaluates multi-venue perpetual funding rates and calendar basis term structures using
//! truncated iterated path signatures $\mathbb{X}^{\le 2}_{[s, t]} \in T((\mathbb{R}^4))$ and
//! anti-symmetric Lévy area lead-lag phase analysis $A_{ij} = \frac{1}{2}(S_2^{ij} - S_2^{ji})$.
//! Generates delta-neutral funding carry and cross-tenor calendar basis dispersion arbitrage signals.

use serde::{Deserialize, Serialize};

/// 4-dimensional observation vector $[F^{(1)}, F^{(2)}, B, I]$:
/// - $F^{(1)}$: Funding rate on venue 1 in annualized % (e.g. 15.0 for 15%).
/// - $F^{(2)}$: Funding rate on venue 2 in annualized %.
/// - $B$: Spot-Perp basis in basis points.
/// - $I$: Normalized order flow imbalance $\in [-1.0, 1.0]$.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FundingBasisPathPoint {
    pub timestamp_sec: f64,
    pub funding_venue1_pct: f64,
    pub funding_venue2_pct: f64,
    pub spot_perp_basis_bps: f64,
    pub ofi_imbalance: f64,
}

impl FundingBasisPathPoint {
    pub fn to_array(&self) -> [f64; 4] {
        [
            self.funding_venue1_pct,
            self.funding_venue2_pct,
            self.spot_perp_basis_bps,
            self.ofi_imbalance,
        ]
    }
}

/// Truncated path signature representation up to degree 2 (4 + 16 = 20 terms) plus Lévy area matrix.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FundingPathSignature2 {
    /// Degree 1 increments $\Delta X^i = X_t^i - X_s^i$.
    pub degree1_increments: [f64; 4],
    /// Degree 2 iterated integrals $S_2^{ij} = \int_s^t (X_u^i - X_s^i) dX_u^j$.
    pub degree2_tensor: [[f64; 4]; 4],
    /// Anti-symmetric Lévy areas $A^{ij} = \frac{1}{2}(S_2^{ij} - S_2^{ji})$.
    pub levy_area: [[f64; 4]; 4],
    /// Total signature Euclidean norm.
    pub signature_norm: f64,
}

/// Configuration for the Path Signature Funding Dispersion Engine.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PathSignatureFundingConfig {
    /// Minimum net funding spread hurdle in annualized % (e.g. 5.0 for 5%).
    pub min_funding_spread_hurdle_pct: f64,
    /// Basis dislocation hurdle in basis points.
    pub basis_dislocation_hurdle_bps: f64,
    /// Minimum absolute Lévy area to confirm lead-lag momentum phase.
    pub min_levy_area_phase_hurdle: f64,
    /// Maximum allowable delta unhedged exposure in USD.
    pub max_unhedged_delta_usd: f64,
}

impl Default for PathSignatureFundingConfig {
    fn default() -> Self {
        Self {
            min_funding_spread_hurdle_pct: 4.5,
            basis_dislocation_hurdle_bps: 12.0,
            min_levy_area_phase_hurdle: 0.15,
            max_unhedged_delta_usd: 100.0,
        }
    }
}

/// Action decision generated by the Funding Dispersion Engine.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub enum FundingDispersionAction {
    /// Long venue 2 perp, short venue 1 perp with synthetic basis lock.
    HarvestFundingCarry {
        spread_pct: f64,
        predicted_basis_bps: f64,
        lead_lag_score: f64,
        target_notional_usd: f64,
    },
    /// Inverted carry: short venue 2 perp, long venue 1 perp.
    InvertedCarryHarvest {
        spread_pct: f64,
        predicted_basis_bps: f64,
        lead_lag_score: f64,
        target_notional_usd: f64,
    },
    /// Spread or basis within fair-value equilibrium band.
    NeutralHold {
        current_spread_pct: f64,
        reason: String,
    },
}

/// Comprehensive signal emitted by the Funding Dispersion Engine.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct FundingDispersionSignal {
    pub symbol: String,
    pub action: FundingDispersionAction,
    pub signature_norm: f64,
    pub levy_lead_lag_area: f64,
    pub expected_basis_bps: f64,
    pub is_executable: bool,
}

/// Engine implementing Path Signature Calibrated Cross-Tenor Funding Rate Carry & Basis Dispersion.
pub struct PathSignatureFundingEngine {
    pub config: PathSignatureFundingConfig,
}

impl PathSignatureFundingEngine {
    pub fn new(config: PathSignatureFundingConfig) -> Self {
        Self { config }
    }

    /// Computes degree 1 and degree 2 iterated path signature using trapezoidal quadrature.
    pub fn compute_signature(
        &self,
        path: &[FundingBasisPathPoint],
    ) -> Option<FundingPathSignature2> {
        if path.len() < 2 {
            return None;
        }

        let n = path.len();
        let start = path[0].to_array();
        let end = path[n - 1].to_array();

        // Degree 1 increments
        let mut deg1 = [0.0; 4];
        for i in 0..4 {
            deg1[i] = end[i] - start[i];
        }

        // Degree 2 iterated integrals using cumulative Riemann-Stieltjes sums
        let mut deg2 = [[0.0; 4]; 4];
        for step in 1..n {
            let p_prev = path[step - 1].to_array();
            let p_curr = path[step].to_array();

            for i in 0..4 {
                // Midpoint value relative to path start
                let mid_i = 0.5 * (p_prev[i] + p_curr[i]) - start[i];
                for j in 0..4 {
                    let d_j = p_curr[j] - p_prev[j];
                    deg2[i][j] += mid_i * d_j;
                }
            }
        }

        // Anti-symmetric Lévy area matrix
        let mut levy = [[0.0; 4]; 4];
        let mut norm_sq = 0.0;
        for i in 0..4 {
            norm_sq += deg1[i] * deg1[i];
            for j in 0..4 {
                levy[i][j] = 0.5 * (deg2[i][j] - deg2[j][i]);
                norm_sq += deg2[i][j] * deg2[i][j];
            }
        }

        Some(FundingPathSignature2 {
            degree1_increments: deg1,
            degree2_tensor: deg2,
            levy_area: levy,
            signature_norm: norm_sq.sqrt(),
        })
    }

    /// Evaluates cross-tenor basis and funding carry opportunity.
    pub fn evaluate_funding_dispersion(
        &self,
        symbol: &str,
        path: &[FundingBasisPathPoint],
        current_spot_usd: f64,
    ) -> FundingDispersionSignal {
        if path.len() < 2 || current_spot_usd <= 0.0 {
            return FundingDispersionSignal {
                symbol: symbol.to_string(),
                action: FundingDispersionAction::NeutralHold {
                    current_spread_pct: 0.0,
                    reason: "Insufficient data points or invalid spot price".into(),
                },
                signature_norm: 0.0,
                levy_lead_lag_area: 0.0,
                expected_basis_bps: 0.0,
                is_executable: false,
            };
        }

        let sig = match self.compute_signature(path) {
            Some(s) => s,
            None => {
                return FundingDispersionSignal {
                    symbol: symbol.to_string(),
                    action: FundingDispersionAction::NeutralHold {
                        current_spread_pct: 0.0,
                        reason: "Signature computation failed".into(),
                    },
                    signature_norm: 0.0,
                    levy_lead_lag_area: 0.0,
                    expected_basis_bps: 0.0,
                    is_executable: false,
                };
            }
        };

        let latest = path.last().unwrap();
        let funding_spread = latest.funding_venue1_pct - latest.funding_venue2_pct;
        let basis_bps = latest.spot_perp_basis_bps;

        // Lévy area between Venue 1 funding (dim 0) and Venue 2 funding (dim 1)
        let levy_f1_f2 = sig.levy_area[0][1];

        // Linear functional prediction of expected basis from signature features
        // w_basis = 0.25 * Delta F1 - 0.20 * Delta F2 + 0.15 * Levy(0, 2)
        let expected_basis = basis_bps + 0.35 * sig.degree1_increments[0]
            - 0.30 * sig.degree1_increments[1]
            + 0.50 * sig.levy_area[0][2];

        let basis_dislocation = (basis_bps - expected_basis).abs();

        let has_phase_or_basis_edge = levy_f1_f2.abs() >= self.config.min_levy_area_phase_hurdle
            || basis_dislocation >= self.config.basis_dislocation_hurdle_bps;

        if funding_spread >= self.config.min_funding_spread_hurdle_pct {
            let base_notional =
                10_000.0 * (funding_spread / self.config.min_funding_spread_hurdle_pct);
            let target_notional = if has_phase_or_basis_edge {
                (base_notional * 1.5).clamp(5_000.0, 50_000.0)
            } else {
                base_notional.clamp(5_000.0, 50_000.0)
            };

            FundingDispersionSignal {
                symbol: symbol.to_string(),
                action: FundingDispersionAction::HarvestFundingCarry {
                    spread_pct: funding_spread,
                    predicted_basis_bps: expected_basis,
                    lead_lag_score: levy_f1_f2,
                    target_notional_usd: target_notional,
                },
                signature_norm: sig.signature_norm,
                levy_lead_lag_area: levy_f1_f2,
                expected_basis_bps: expected_basis,
                is_executable: true,
            }
        } else if funding_spread <= -self.config.min_funding_spread_hurdle_pct {
            let base_notional =
                10_000.0 * (funding_spread.abs() / self.config.min_funding_spread_hurdle_pct);
            let target_notional = if has_phase_or_basis_edge {
                (base_notional * 1.5).clamp(5_000.0, 50_000.0)
            } else {
                base_notional.clamp(5_000.0, 50_000.0)
            };

            FundingDispersionSignal {
                symbol: symbol.to_string(),
                action: FundingDispersionAction::InvertedCarryHarvest {
                    spread_pct: funding_spread,
                    predicted_basis_bps: expected_basis,
                    lead_lag_score: levy_f1_f2,
                    target_notional_usd: target_notional,
                },
                signature_norm: sig.signature_norm,
                levy_lead_lag_area: levy_f1_f2,
                expected_basis_bps: expected_basis,
                is_executable: true,
            }
        } else {
            FundingDispersionSignal {
                symbol: symbol.to_string(),
                action: FundingDispersionAction::NeutralHold {
                    current_spread_pct: funding_spread,
                    reason: format!(
                        "Spread {:.2}% below hurdle {:.2}% or insufficient phase/basis edge",
                        funding_spread, self.config.min_funding_spread_hurdle_pct
                    ),
                },
                signature_norm: sig.signature_norm,
                levy_lead_lag_area: levy_f1_f2,
                expected_basis_bps: expected_basis,
                is_executable: false,
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_signature_computation_on_path() {
        let engine = PathSignatureFundingEngine::new(PathSignatureFundingConfig::default());
        let path = vec![
            FundingBasisPathPoint {
                timestamp_sec: 0.0,
                funding_venue1_pct: 12.0,
                funding_venue2_pct: 5.0,
                spot_perp_basis_bps: 15.0,
                ofi_imbalance: 0.1,
            },
            FundingBasisPathPoint {
                timestamp_sec: 1.0,
                funding_venue1_pct: 14.0,
                funding_venue2_pct: 5.5,
                spot_perp_basis_bps: 18.0,
                ofi_imbalance: 0.3,
            },
            FundingBasisPathPoint {
                timestamp_sec: 2.0,
                funding_venue1_pct: 18.0,
                funding_venue2_pct: 6.0,
                spot_perp_basis_bps: 22.0,
                ofi_imbalance: 0.4,
            },
        ];

        let sig = engine
            .compute_signature(&path)
            .expect("Signature compute failed");
        assert_eq!(sig.degree1_increments[0], 6.0); // 18.0 - 12.0
        assert_eq!(sig.degree1_increments[1], 1.0); // 6.0 - 5.0
        assert!(sig.signature_norm > 0.0);

        // Anti-symmetry of Lévy area
        for i in 0..4 {
            for j in 0..4 {
                assert!((sig.levy_area[i][j] + sig.levy_area[j][i]).abs() < 1e-10);
            }
        }
    }

    #[test]
    fn test_funding_dispersion_signal_generation() {
        let engine = PathSignatureFundingEngine::new(PathSignatureFundingConfig {
            min_funding_spread_hurdle_pct: 5.0,
            min_levy_area_phase_hurdle: 0.10,
            ..Default::default()
        });

        let path = vec![
            FundingBasisPathPoint {
                timestamp_sec: 0.0,
                funding_venue1_pct: 20.0,
                funding_venue2_pct: 5.0,
                spot_perp_basis_bps: 30.0,
                ofi_imbalance: 0.2,
            },
            FundingBasisPathPoint {
                timestamp_sec: 1.0,
                funding_venue1_pct: 22.0,
                funding_venue2_pct: 4.5,
                spot_perp_basis_bps: 35.0,
                ofi_imbalance: 0.5,
            },
        ];

        let signal = engine.evaluate_funding_dispersion("ETH", &path, 3200.0);
        assert!(signal.is_executable);
        match signal.action {
            FundingDispersionAction::HarvestFundingCarry {
                spread_pct,
                target_notional_usd,
                ..
            } => {
                assert!(spread_pct >= 15.0);
                assert!(target_notional_usd >= 10_000.0);
            }
            _ => panic!("Expected HarvestFundingCarry"),
        }
    }

    #[test]
    fn test_neutral_hold_when_spread_is_tight() {
        let engine = PathSignatureFundingEngine::new(PathSignatureFundingConfig::default());
        let path = vec![
            FundingBasisPathPoint {
                timestamp_sec: 0.0,
                funding_venue1_pct: 6.0,
                funding_venue2_pct: 5.5,
                spot_perp_basis_bps: 5.0,
                ofi_imbalance: 0.0,
            },
            FundingBasisPathPoint {
                timestamp_sec: 1.0,
                funding_venue1_pct: 6.2,
                funding_venue2_pct: 5.8,
                spot_perp_basis_bps: 5.5,
                ofi_imbalance: 0.05,
            },
        ];

        let signal = engine.evaluate_funding_dispersion("BTC", &path, 68000.0);
        assert!(!signal.is_executable);
        match signal.action {
            FundingDispersionAction::NeutralHold { .. } => {}
            _ => panic!("Expected NeutralHold for tight spread"),
        }
    }
}
