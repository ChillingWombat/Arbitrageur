use std::sync::Arc;
use tracing::debug;
use arbitrager_core::exchange::ExchangeAdapter;
use arbitrager_core::types::{dec, Decimal, Side};
use arbitrager_execution::coordinator::{ArbitrageExecutionResult, AtomicArbitrageCoordinator};
use arbitrager_math::rolling_stats::RollingWindowStats;
use arbitrager_math::spatial_spread::evaluate_spatial_spread;

/// Direction of spatial price spread arbitrage.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SpatialDirection {
    /// Buy Venue A (Ask), Sell Venue B (Bid)
    BuyASellB,
    /// Buy Venue B (Ask), Sell Venue A (Bid)
    BuyBSellA,
}

/// Signal generated by spatial price difference strategy.
#[derive(Debug, Clone)]
pub struct SpatialSignal {
    pub direction: SpatialDirection,
    pub symbol: String,
    pub spread: Decimal,
    pub spread_bps: Decimal,
    pub executable_qty: Decimal,
    pub expected_profit_usd: Decimal,
}

pub struct SpatialPriceArbStrategy {
    pub symbol: String,
    pub exchange_a: Arc<dyn ExchangeAdapter>,
    pub exchange_b: Arc<dyn ExchangeAdapter>,
    pub target_profit_bps: Decimal,
    pub max_slippage_bps: Decimal,
    pub order_qty: Decimal,
    pub fee_a_bps: Decimal,
    pub fee_b_bps: Decimal,
    pub stats_a_to_b: RollingWindowStats,
    pub stats_b_to_a: RollingWindowStats,
    pub min_samples: usize,
}

impl SpatialPriceArbStrategy {
    #[allow(clippy::too_many_arguments)]
    pub fn new(
        symbol: impl Into<String>,
        exchange_a: Arc<dyn ExchangeAdapter>,
        exchange_b: Arc<dyn ExchangeAdapter>,
        target_profit_bps: Decimal,
        max_slippage_bps: Decimal,
        order_qty: Decimal,
        fee_a_bps: Decimal,
        fee_b_bps: Decimal,
        window_size: usize,
        min_samples: usize,
    ) -> Self {
        Self {
            symbol: symbol.into(),
            exchange_a,
            exchange_b,
            target_profit_bps,
            max_slippage_bps,
            order_qty,
            fee_a_bps,
            fee_b_bps,
            stats_a_to_b: RollingWindowStats::new(window_size),
            stats_b_to_a: RollingWindowStats::new(window_size),
            min_samples,
        }
    }

    /// Evaluates current orderbooks and returns an arbitrage signal if profitable.
    pub async fn evaluate_opportunity(&mut self) -> anyhow::Result<Option<SpatialSignal>> {
        let (book_a, book_b) = tokio::try_join!(
            self.exchange_a.fetch_orderbook(&self.symbol),
            self.exchange_b.fetch_orderbook(&self.symbol)
        )?;

        let bid_a = book_a.best_bid_price().unwrap_or(dec!(0));
        let ask_a = book_a.best_ask_price().unwrap_or(dec!(0));
        let bid_b = book_b.best_bid_price().unwrap_or(dec!(0));
        let ask_b = book_b.best_ask_price().unwrap_or(dec!(0));

        if bid_a <= dec!(0) || ask_a <= dec!(0) || bid_b <= dec!(0) || ask_b <= dec!(0) {
            return Ok(None);
        }

        // Direction 1: Buy A (ask_a), Sell B (bid_b) -> Spread = bid_b - ask_a
        let spread_buy_a_sell_b = bid_b - ask_a;
        // Direction 2: Buy B (ask_b), Sell A (bid_a) -> Spread = bid_a - ask_b
        let spread_buy_b_sell_a = bid_a - ask_b;

        self.stats_a_to_b.push(spread_buy_a_sell_b);
        self.stats_b_to_a.push(spread_buy_b_sell_a);

        if !self.stats_a_to_b.is_warmed_up(self.min_samples) {
            debug!(
                "[{}] Warming up spatial window: {}/{} samples",
                self.symbol,
                self.stats_a_to_b.count(),
                self.min_samples
            );
            return Ok(None);
        }

        // Evaluate depth-weighted executable opportunity Direction 1: Buy A, Sell B
        if let Some(opp1) = evaluate_spatial_spread(&book_a, &book_b, self.fee_a_bps, self.fee_b_bps, self.order_qty) {
            if opp1.net_profit_bps >= self.target_profit_bps {
                return Ok(Some(SpatialSignal {
                    direction: SpatialDirection::BuyASellB,
                    symbol: self.symbol.clone(),
                    spread: opp1.gross_spread,
                    spread_bps: opp1.net_profit_bps,
                    executable_qty: opp1.executable_qty,
                    expected_profit_usd: opp1.total_net_profit_usd,
                }));
            }
        }

        // Evaluate depth-weighted executable opportunity Direction 2: Buy B, Sell A
        if let Some(opp2) = evaluate_spatial_spread(&book_b, &book_a, self.fee_b_bps, self.fee_a_bps, self.order_qty) {
            if opp2.net_profit_bps >= self.target_profit_bps {
                return Ok(Some(SpatialSignal {
                    direction: SpatialDirection::BuyBSellA,
                    symbol: self.symbol.clone(),
                    spread: opp2.gross_spread,
                    spread_bps: opp2.net_profit_bps,
                    executable_qty: opp2.executable_qty,
                    expected_profit_usd: opp2.total_net_profit_usd,
                }));
            }
        }

        Ok(None)
    }

    /// Execute the detected signal atomically using the coordinator.
    pub async fn execute_signal(
        &self,
        signal: &SpatialSignal,
        coordinator: &AtomicArbitrageCoordinator,
    ) -> ArbitrageExecutionResult {
        match signal.direction {
            SpatialDirection::BuyASellB => {
                let (ticker_a, ticker_b) = tokio::join!(
                    self.exchange_a.fetch_ticker(&self.symbol),
                    self.exchange_b.fetch_ticker(&self.symbol),
                );
                let ref_a = ticker_a.map(|t| t.ask).unwrap_or(dec!(0));
                let ref_b = ticker_b.map(|t| t.bid).unwrap_or(dec!(0));

                // Fail closed: a missing reference price must never become an
                // extreme IOC price (unbounded buy / dust sell). Reject cleanly.
                if ref_a <= dec!(0) || ref_b <= dec!(0) {
                    return ArbitrageExecutionResult::BothFailed {
                        error_a: format!("missing reference ask for {}", self.symbol),
                        error_b: format!("missing reference bid for {}", self.symbol),
                    };
                }

                let order_a = coordinator.router().build_ioc_order(
                    self.exchange_a.venue_id(),
                    &self.symbol,
                    Side::Buy,
                    ref_a,
                    signal.executable_qty,
                );

                let order_b = coordinator.router().build_ioc_order(
                    self.exchange_b.venue_id(),
                    &self.symbol,
                    Side::Sell,
                    ref_b,
                    signal.executable_qty,
                );

                coordinator.execute_two_leg(&self.exchange_a, order_a, &self.exchange_b, order_b).await
            }
            SpatialDirection::BuyBSellA => {
                let (ticker_b, ticker_a) = tokio::join!(
                    self.exchange_b.fetch_ticker(&self.symbol),
                    self.exchange_a.fetch_ticker(&self.symbol),
                );
                let ref_b = ticker_b.map(|t| t.ask).unwrap_or(dec!(0));
                let ref_a = ticker_a.map(|t| t.bid).unwrap_or(dec!(0));

                if ref_b <= dec!(0) || ref_a <= dec!(0) {
                    return ArbitrageExecutionResult::BothFailed {
                        error_a: format!("missing reference bid for {}", self.symbol),
                        error_b: format!("missing reference ask for {}", self.symbol),
                    };
                }

                let order_b = coordinator.router().build_ioc_order(
                    self.exchange_b.venue_id(),
                    &self.symbol,
                    Side::Buy,
                    ref_b,
                    signal.executable_qty,
                );

                let order_a = coordinator.router().build_ioc_order(
                    self.exchange_a.venue_id(),
                    &self.symbol,
                    Side::Sell,
                    ref_a,
                    signal.executable_qty,
                );

                coordinator.execute_two_leg(&self.exchange_b, order_b, &self.exchange_a, order_a).await
            }
        }
    }
}
